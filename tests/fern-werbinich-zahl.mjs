// Zwei simulierte Handys spielen „Wer bin ich?“ und „Zahl erraten“ im Fern-Modus. Aufruf: node tests/fern-werbinich-zahl.mjs [bilder-ordner]
import { chromium, openPage } from './helpers.mjs';
import { mkdirSync } from 'node:fs';
const OUT = process.argv[2] || 'test-bilder'; // Screenshots landen hier
mkdirSync(OUT, { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
const prefs = { mode: 'remote', code: 'testraum43' };
const A = await openPage(browser, { context: ctx, ns: 'a', query: 'net=local', store: { me: 'jos', prefs } });
const B = await openPage(browser, { context: ctx, ns: 'b', query: 'net=local', store: { me: 'joh', prefs, themeFor: { jos: 'baby', joh: 'lila' } } });
const a = A.page, b = B.page;
const W = (ms) => a.waitForTimeout(ms);
await a.click('.wer-name.jos'); await b.click('.wer-name.joh'); await W(2500);
// ---------- Wer bin ich? ----------
await a.click('[data-game="whoami"]'); await W(600);
await a.click('[data-a="start"]'); await W(800);
await a.click('.wa-pick .btn.primary'); await W(800);
await b.click('.invite .btn.primary'); await W(800);
await b.click('.picker .seg-opt[data-value="own"]');
await b.fill('.picker-own input', 'Elsa');
await b.click('.wa-pick .btn.primary'); await W(1200);
const johChar = (await a.textContent('.postit.joh .pi-val')).trim();
console.log('A sieht Johanns Figur:', johChar);
await a.fill('.compose-row input', 'Bin ich eine Prinzessin'); await a.click('.compose-row button'); await W(900);
await b.screenshot({ path: `${OUT}/r2-B-question.png` });
await b.click('.ans[data-a="ja"]'); await W(900);
await a.click('.quick .chip >> nth=9'); await W(900);
await b.click('.ans[data-a="nein"]'); await W(1000);
await b.screenshot({ path: `${OUT}/r2-B-myturn.png` });
await b.click('[data-a="solve"]'); await W(500);
const end = johChar.toLowerCase().endsWith('x') ? 'q' : 'x';
const typo = johChar.length > 4 ? johChar.slice(0, -1) + end : johChar + end;
await b.fill('.sheet input', typo); await b.click('.sheet .btn.primary'); await W(1000);
await a.screenshot({ path: `${OUT}/r2-A-judge.png` });
await a.click('.ans[data-a="ok"]'); await W(1200);
await a.click('[data-a="solve"]'); await W(500);
await a.fill('.sheet input', 'elsa'); await a.click('.sheet .btn.primary'); await W(2500);
await a.screenshot({ path: `${OUT}/r2-A-end.png` });
await b.screenshot({ path: `${OUT}/r2-B-end.png` });
console.log('A:', (await a.textContent('.result')).replace(/\s+/g, ' ').trim());
console.log('B:', (await b.textContent('.result')).replace(/\s+/g, ' ').trim());
await a.click('.result .btn:not(.primary)'); await b.click('.result .btn:not(.primary)'); await W(1500);
// ---------- Zahl erraten ----------
await a.click('[data-game="number"]'); await W(600);
await a.click('[data-a="start"]'); await W(800);
for (const k of ['4', '2']) await a.click(`.np-key[data-k="${k}"]`);
await a.click('.numpad .btn.primary'); await W(800);
await b.click('.invite .btn.primary'); await W(800);
await b.click('.np-key[data-k="7"]'); await b.click('.numpad .btn.primary'); await W(1200);
await a.click('[data-a="ideas"]'); await W(500);
await a.click('.idea[data-id="gerade"]'); await W(1000);
await b.screenshot({ path: `${OUT}/r2-B-card.png` });
console.log('B Karte:', (await b.textContent('.q-card')).replace(/\s+/g, ' ').trim());
await b.click('.ans[data-a="nein"]'); await W(1500);
console.log('A gestrichen:', await a.$$eval('.nc.x', (n) => n.length));
await a.screenshot({ path: `${OUT}/r2-A-board.png` });
await b.click('[data-a="guess"]'); await W(500);
for (const k of ['4', '2']) await b.click(`.sheet .np-key[data-k="${k}"]`);
await b.click('.sheet .numpad .btn.primary'); await W(1200);
await a.click('[data-a="guess"]'); await W(500);
await a.click('.sheet .np-key[data-k="7"]'); await a.click('.sheet .numpad .btn.primary'); await W(2500);
console.log('A:', (await a.textContent('.result')).replace(/\s+/g, ' ').trim());
console.log('B:', (await b.textContent('.result')).replace(/\s+/g, ' ').trim());
await b.screenshot({ path: `${OUT}/r2-B-nu-end.png` });
await a.click('.result .btn:not(.primary)'); await b.click('.result .btn:not(.primary)'); await W(1500);
console.log('Bilanz A:', (await a.textContent('.score-main')).replace(/\s+/g, ' ').trim(), '| B:', (await b.textContent('.score-main')).replace(/\s+/g, ' ').trim());
console.log('ERR A', JSON.stringify(A.errors), 'ERR B', JSON.stringify(B.errors));
await browser.close();
